-- 新しい匿名プレイヤーには、Authユーザー作成時に未使用候補を1つ固定割当する。
-- 候補が尽きた場合でも匿名ログイン自体は失敗させない。
create or replace function public.assign_player_nickname_on_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_nickname_id bigint;
begin
  if coalesce(new.is_anonymous, false) is not true then
    return new;
  end if;

  if exists (
    select 1
    from public.player_profiles pp
    where pp.user_id = new.id
  ) then
    return new;
  end if;

  select np.id
  into v_nickname_id
  from public.nickname_pool np
  where np.is_active = true
    and not exists (
      select 1
      from public.player_profiles pp
      where pp.nickname_id = np.id
    )
  order by random()
  limit 1
  for update skip locked;

  if v_nickname_id is null then
    return new;
  end if;

  insert into public.player_profiles (
    user_id,
    nickname_id
  )
  values (
    new.id,
    v_nickname_id
  )
  on conflict (user_id) do nothing;

  return new;

exception
  when unique_violation then
    -- 万一の同時割当競合でもAuth登録自体は止めない。
    return new;
end;
$$;

revoke all on function public.assign_player_nickname_on_auth_user() from public;
revoke all on function public.assign_player_nickname_on_auth_user() from anon;
revoke all on function public.assign_player_nickname_on_auth_user() from authenticated;

drop trigger if exists assign_player_nickname_after_auth_user_insert on auth.users;

create trigger assign_player_nickname_after_auth_user_insert
after insert on auth.users
for each row
execute function public.assign_player_nickname_on_auth_user();

-- 既存プレイヤーにも、現在の検定データに登場する匿名 user_id から固定名を割り当てる。
do $$
declare
  v_user_id uuid;
  v_nickname_id bigint;
begin
  for v_user_id in
    select distinct u.user_id
    from (
      select user_id from public.quiz_sessions where user_id is not null
      union
      select user_id from public.question_reports where user_id is not null
      union
      select user_id from public.first_answers where user_id is not null
      union
      select user_id from public.quiz_answers where user_id is not null
    ) u
    join auth.users au
      on au.id = u.user_id
    left join public.player_profiles pp
      on pp.user_id = u.user_id
    where pp.user_id is null
      and coalesce(au.is_anonymous, false) = true
  loop
    select np.id
    into v_nickname_id
    from public.nickname_pool np
    where np.is_active = true
      and not exists (
        select 1
        from public.player_profiles existing_profile
        where existing_profile.nickname_id = np.id
      )
    order by random()
    limit 1
    for update skip locked;

    exit when v_nickname_id is null;

    insert into public.player_profiles (
      user_id,
      nickname_id
    )
    values (
      v_user_id,
      v_nickname_id
    )
    on conflict (user_id) do nothing;
  end loop;
end;
$$;

