-- アスカ見参 廃人検定
-- プレイヤー固定ニックネーム用マスタ・割当テーブル
-- 初期候補: 通常名称 560件 + 99段階モンスター派生 294件 = 合計854件
--
-- 方針:
-- 1. 匿名Authの user_id ごとに一度だけニックネームを割り当てる
-- 2. 同じ user_id には以後ずっと同じ名前を返す
-- 3. nickname_id を UNIQUE にし、候補が尽きるまでは重複割当しない
-- 4. 候補追加後も既存プレイヤーの名前は変えない

begin;

create table if not exists public.nickname_pool (
  id bigserial primary key,
  name text not null unique,
  category text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.player_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nickname_id bigint not null unique references public.nickname_pool(id) on delete restrict,
  assigned_at timestamptz not null default now()
);

create index if not exists nickname_pool_active_idx
  on public.nickname_pool (is_active);

create index if not exists player_profiles_nickname_idx
  on public.player_profiles (nickname_id);

alter table public.nickname_pool enable row level security;
alter table public.player_profiles enable row level security;

grant select on public.nickname_pool to authenticated;
grant select on public.player_profiles to authenticated;

drop policy if exists "admins can read nickname pool" on public.nickname_pool;
create policy "admins can read nickname pool"
  on public.nickname_pool
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.admin_users au
      where au.user_id = auth.uid()
    )
  );

drop policy if exists "players can read own profile" on public.player_profiles;
create policy "players can read own profile"
  on public.player_profiles
  for select
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "admins can read all player profiles" on public.player_profiles;
create policy "admins can read all player profiles"
  on public.player_profiles
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.admin_users au
      where au.user_id = auth.uid()
    )
  );

